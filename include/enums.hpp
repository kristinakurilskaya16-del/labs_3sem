#pragma once

/** @file enums.hpp
 * @brief Стратегии предобработки и порядок хранения матрицы.
 */

/** @brief Способ заполнения числовых пропусков по готовой статистике. */
enum class NumericImputation
{
    /** @brief Заполнить пропуски средним из переданной статистики. */
    Mean,
    /** @brief Заполнить пропуски медианой из переданной статистики. */
    Median,
    /** @brief Нулевое значение. */
    Zero
};

/**
 * @brief Способ масштабирования числовых признаков.
 *
 * @note Для способов, использующих деление, при нулевом
 * знаменателе результат преобразования равен нулю.
 */
enum class Scaling
{
    /** @brief Оставить значение без изменения. */
    None,
    /** @brief Вычесть минимум и разделить на размах. */
    MinMax,
    /** @brief Вычесть среднее и разделить на стандартное отклонение. */
    Standard,
    /** @brief Вычесть медиану и разделить на межквартильный размах. */
    Robust
};

/** @brief Способ представления категорий в числовой матрице. */
enum class Encoding
{
    /** @brief Отдельный бинарный столбец на категорию. */
    OneHot,
    /** @brief Заменить категорию её номером в списке категорий, начиная с нуля. */
    Ordinal
};

/** @brief Физический порядок элементов в непрерывном буфере матрицы. */
enum class Layout
{
    /** @brief Последовательное хранение строк. */
    RowMajor,
    /** @brief Последовательное хранение столбцов. */
    ColumnMajor
};
